function mtcPlainGymText(text) {
  let out = text;
  for (const [hard, plain] of MTC_GYM_PLAIN_PHRASES) {
    const escaped = hard.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    out = out.replace(new RegExp(`\\b${escaped}\\b`, "gi"), (found) =>
      found[0] === found[0].toUpperCase()
        ? plain[0].toUpperCase() + plain.slice(1)
        : plain
    );
  }
  out = out.replace(/\s+/g, " ").trim();
  const countWords = (sentence) =>
    (sentence.match(/[A-Za-zÀ-ÿ0-9£%]+(?:['’-][A-Za-zÀ-ÿ0-9]+)*/g) || []).length;
  out = out
    .replace(/;\s+/g, ". ")
    .replace(/\s+—\s+(?=(?:and|but|so|the|this|that|it|you|we|they|someone|anything|none)\b)/gi, ". ");
  out = out.split(/(?<=[.!?])\s+/).map((sentence) => {
    if (countWords(sentence) <= 24) return sentence;
    return sentence.replace(/,\s+(and|but|so)\s+/i, (match, joiner) => {
      if (joiner.toLowerCase() === "but") return ". However, ";
      if (joiner.toLowerCase() === "so") return ". Therefore, ";
      return ". ";
    });
  }).join(" ");
  return out
    .replace(/\.\s+And\s+/g, ". ")
    .replace(/\.\s+But\s+/g, ". However, ")
    .replace(/\.\s+So\s+/g, ". Therefore, ")
    .replace(/(^|[.!?]\s+)([a-z])/g, (match, start, letter) => start + letter.toUpperCase());
}

function mtcSimplifyGymContent(value, parentKey = "") {
  if (parentKey === "band" && typeof value === "string") return value.toLowerCase();
  const structural = new Set(["id", "format", "muscle", "frameworks", "lifeAreas", "emoji", "bucket", "value"]);
  if (structural.has(parentKey)) return value;
  if (typeof value === "string") return mtcPlainGymText(value);
  if (Array.isArray(value)) return value.map((item) => mtcSimplifyGymContent(item, parentKey));
  if (value && typeof value === "object") {
    for (const key of Object.keys(value)) value[key] = mtcSimplifyGymContent(value[key], key);
  }
  return value;
}

